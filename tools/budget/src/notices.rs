//! The release's third-party notices (REQ-BUD-5, AD-9; part 10d, D-108). The binary is static, so it is a copy of
//! everything it links: every crate it reaches on the release's target, read from `Cargo.lock` through one `cargo
//! metadata` filtered to that target, with the licence its manifest declares and every licence text its package
//! carries; and the toolchain's libraries, which no lock file names: the Rust standard library, whose notices the
//! toolchain ships in `COPYRIGHT-library.html`, copied as it is, and musl libc and LLVM libunwind, whose texts are kept
//! beside this tool for the versions the toolchain holds. The same lock file and toolchain give the same bytes.

use crate::budget::{BINARY_PACKAGE, RINGS};
use crate::deps;
use crate::json::{self, Value};
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::process::Command;

/// The release's one target: Linux on ARM64 alone (D-097 point 10).
pub const TARGET: &str = "aarch64-unknown-linux-musl";
/// The notices' file in the release.
pub const FILE: &str = "THIRD-PARTY-NOTICES";
/// The standard library's own notices in the release, the toolchain's `COPYRIGHT-library.html` as it is.
pub const STD_FILE: &str = "THIRD-PARTY-NOTICES-std.html";

/// musl libc's `COPYRIGHT` at its tag `v1.2.5` (git.musl-libc.org), the version of the toolchain's `libc.a`.
const MUSL: &str = "1.2.5";
const MUSL_TEXT: &str = include_str!("../notices/musl-1.2.5-COPYRIGHT");
/// LLVM libunwind's `LICENSE.TXT` at `llvmorg-23.1.1` (github.com/llvm/llvm-project), the toolchain's LLVM.
const LLVM: &str = "23.1.1";
const LIBUNWIND_TEXT: &str = include_str!("../notices/llvm-23.1.1-libunwind-LICENSE.TXT");

/// What the binary links: its name, version and declared licence, and the licence texts it carries by file name.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Linked {
    pub name: String,
    pub version: String,
    pub license: String,
    pub texts: Vec<(String, String)>,
}

/// What the notices are made of.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Inputs {
    /// Fabrewk's version.
    pub version: String,
    /// The toolchain's `rustc` release.
    pub rustc: String,
    /// The crates, by name and version.
    pub crates: Vec<Linked>,
    /// The toolchain's libraries but the standard library, whose notices are their own file.
    pub toolchain: Vec<Linked>,
}

const RULE: &str = "================================================================================\n";
const THIN: &str = "--------------------------------------------------------------------------------\n";

/// The notices' text: the list of what the binary links, then every distinct licence text once, with what carries it,
/// in the list's order.
pub fn render(i: &Inputs) -> String {
    let mut out = format!("Third-party notices of fabrewk {} for {TARGET}\n\n", i.version);
    out += &format!(
        "Generated by `budget notices` from Cargo.lock and the toolchain, rustc {}; a fresh generation from the\n\
         same lock file and toolchain gives the same bytes.\n\n",
        i.rustc
    );
    out += "Fabrewk's own crates are under MIT OR Apache-2.0 (LICENSE-MIT, LICENSE-APACHE, NOTICE). The binary is\n\
            static: it links the crates and the toolchain's libraries below, each under the licence it declares.\n\
            Every licence text they carry follows, each distinct text once, with what carries it.\n\n\
            Crates, from Cargo.lock:\n\n";
    for c in &i.crates {
        out += &format!("  {} {}: {}\n", c.name, c.version, c.license);
    }
    out += "\nThe toolchain's libraries:\n\n";
    out +=
        &format!("  The Rust standard library {}: MIT OR Apache-2.0, with the notices of what it holds, as\n", i.rustc);
    out += &format!("    the toolchain ships them, in {STD_FILE}\n");
    for c in &i.toolchain {
        out += &format!("  {} {}: {}\n", c.name, c.version, c.license);
    }
    let mut order: Vec<&str> = Vec::new();
    let mut carriers: BTreeMap<&str, Vec<String>> = BTreeMap::new();
    for c in i.crates.iter().chain(&i.toolchain) {
        for (file, text) in &c.texts {
            let by = carriers.entry(text).or_insert_with(|| {
                order.push(text);
                Vec::new()
            });
            by.push(format!("{} {}, {file}", c.name, c.version));
        }
    }
    for (n, text) in order.iter().enumerate() {
        out += &format!("\n{RULE}Text {} of {}, carried by:\n", n + 1, order.len());
        for by in &carriers[text] {
            out += &format!("  {by}\n");
        }
        out += THIN;
        out += text;
        if !text.ends_with('\n') {
            out.push('\n');
        }
    }
    out
}

/// Whether a package's file is a licence text: its name, in any case, starts as one does.
pub fn is_licence_text(name: &str) -> bool {
    let upper = name.to_ascii_uppercase();
    ["LICENSE", "LICENCE", "COPYING", "COPYRIGHT", "NOTICE", "UNLICENSE"].iter().any(|p| upper.starts_with(p))
}

/// The licence texts a package's directory holds at its top, by file name; none is an error, since the notice could
/// not travel with the binary.
pub fn licence_texts(dir: &Path, who: &str) -> Result<Vec<(String, String)>, String> {
    let mut texts = Vec::new();
    for entry in std::fs::read_dir(dir).map_err(|e| format!("{}: {e}", dir.display()))? {
        let entry = entry.map_err(|e| format!("{}: {e}", dir.display()))?;
        let name = entry.file_name().to_string_lossy().into_owned();
        if is_licence_text(&name) && entry.file_type().map_err(|e| e.to_string())?.is_file() {
            let path = entry.path();
            let text = std::fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
            texts.push((name, text));
        }
    }
    if texts.is_empty() {
        return Err(format!("{who} carries no licence text in {}, so its notice cannot travel", dir.display()));
    }
    texts.sort();
    Ok(texts)
}

/// The crates the binary reaches on [`TARGET`], from `cargo metadata`'s output filtered to it, sorted by name and
/// version.
pub fn crates(metadata: &str, own: &[PathBuf]) -> Result<Vec<Linked>, String> {
    // The walk is the budget's; its closed-world problems are `budget check`'s to report.
    let report = deps::analyse(metadata, BINARY_PACKAGE, own, &[])?;
    let doc = json::parse(metadata)?;
    let text = |v: &Value, key: &str| v.get(key).and_then(Value::as_str).map(str::to_owned);
    let mut crates = Vec::new();
    for p in doc.get("packages").map_or(&[][..], Value::as_array) {
        if !text(p, "id").is_some_and(|id| report.all.contains_key(&id)) {
            continue;
        }
        let (name, version) = (text(p, "name").unwrap_or_default(), text(p, "version").unwrap_or_default());
        let who = format!("{name} {version}");
        let license = text(p, "license").ok_or_else(|| format!("{who} declares no licence"))?;
        let manifest = text(p, "manifest_path").ok_or_else(|| format!("{who}: no manifest_path"))?;
        let texts = licence_texts(Path::new(&manifest).parent().unwrap_or(Path::new("")), &who)?;
        crates.push(Linked { name, version, license, texts });
    }
    crates.sort_by(|a, b| (&a.name, &a.version).cmp(&(&b.name, &b.version)));
    Ok(crates)
}

/// The toolchain `rustc` names: its release, its LLVM and its sysroot.
pub struct Toolchain {
    pub release: String,
    pub llvm: String,
    pub sysroot: PathBuf,
}

fn run(program: &str, args: &[&str]) -> Result<String, String> {
    let out = Command::new(program).args(args).output().map_err(|e| format!("cannot run {program}: {e}"))?;
    if !out.status.success() {
        return Err(format!("{program} {} failed: {}", args.join(" "), String::from_utf8_lossy(&out.stderr).trim()));
    }
    String::from_utf8(out.stdout).map_err(|_| format!("{program} printed non-UTF-8"))
}

/// Reads the toolchain from `rustc` (`RUSTC`, else the one on `PATH`, which rustup resolves to the toolchain that
/// runs this tool).
pub fn toolchain() -> Result<Toolchain, String> {
    let rustc = std::env::var("RUSTC").unwrap_or_else(|_| "rustc".to_owned());
    let verbose = run(&rustc, &["-vV"])?;
    let field = |key: &str| {
        verbose.lines().find_map(|l| l.strip_prefix(key)).map(str::to_owned).ok_or(format!("rustc -vV: no {key}"))
    };
    let sysroot = run(&rustc, &["--print", "sysroot"])?;
    Ok(Toolchain { release: field("release: ")?, llvm: field("LLVM version: ")?, sysroot: sysroot.trim().into() })
}

/// The toolchain's libraries the binary links, but the standard library, checked against the toolchain: its LLVM is
/// the one libunwind's text is for, and its musl `libc.a` names the version musl's text is for.
pub fn toolchain_libraries(t: &Toolchain) -> Result<Vec<Linked>, String> {
    if t.llvm != LLVM {
        return Err(format!("the toolchain's LLVM is {}; the libunwind text kept is for {LLVM}", t.llvm));
    }
    let libc = t.sysroot.join(format!("lib/rustlib/{TARGET}/lib/self-contained/libc.a"));
    let bytes = std::fs::read(&libc).map_err(|e| format!("{}: {e}", libc.display()))?;
    let marker = format!("\0{MUSL}\0");
    if !bytes.windows(marker.len()).any(|w| w == marker.as_bytes()) {
        return Err(format!("{} does not name musl {MUSL}, the version of the text kept", libc.display()));
    }
    let linked = |name: &str, version: &str, license: &str, file: &str, text: &str| Linked {
        name: name.to_owned(),
        version: version.to_owned(),
        license: license.to_owned(),
        texts: vec![(file.to_owned(), text.to_owned())],
    };
    Ok(vec![
        linked("musl libc", MUSL, "MIT", "COPYRIGHT", MUSL_TEXT),
        linked("LLVM libunwind", LLVM, "Apache-2.0 WITH LLVM-exception", "LICENSE.TXT", LIBUNWIND_TEXT),
    ])
}

/// The standard library's notices as the toolchain ships them.
pub fn std_notices(t: &Toolchain) -> Result<Vec<u8>, String> {
    let path = t.sysroot.join("share/doc/rust/COPYRIGHT-library.html");
    std::fs::read(&path).map_err(|e| format!("{}: {e}; the toolchain must ship its notices", path.display()))
}

/// Generates both files for the workspace at `root`: the notices' text and the standard library's notices.
pub fn generate(root: &Path) -> Result<(String, Vec<u8>), String> {
    let out = Command::new(crate::cargo())
        .current_dir(root)
        .args(["metadata", "--locked", "--offline", "--format-version", "1", "--filter-platform", TARGET])
        .output()
        .map_err(|e| format!("cannot run cargo: {e}"))?;
    if !out.status.success() {
        return Err(format!("cargo metadata failed: {}", String::from_utf8_lossy(&out.stderr).trim()));
    }
    let metadata = String::from_utf8(out.stdout).map_err(|_| "cargo metadata printed non-UTF-8".to_string())?;
    let t = toolchain()?;
    let inputs = Inputs {
        version: env!("CARGO_PKG_VERSION").to_owned(),
        rustc: t.release.clone(),
        crates: crates(&metadata, &crate::own_packages(root, RINGS))?,
        toolchain: toolchain_libraries(&t)?,
    };
    Ok((render(&inputs), std_notices(&t)?))
}

/// Writes both files into the directory `dir`, which must exist.
pub fn write(root: &Path, dir: &Path) -> Result<(), String> {
    let (text, std) = generate(root)?;
    std::fs::write(dir.join(FILE), text).map_err(|e| format!("{}: {e}", dir.join(FILE).display()))?;
    std::fs::write(dir.join(STD_FILE), std).map_err(|e| format!("{}: {e}", dir.join(STD_FILE).display()))
}
